import librosa
import numpy as np
from scipy.ndimage import zoom

def preprocess_audio_for_inference(
    file_path,
    sample_rate=16000,
    duration=2.0,
    n_fft=2048,
    hop_length=512,
    n_mels=128
):
    """
    Preprocess a WAV file EXACTLY like preprocess_for2sec_3ch.py
    Output: (1, 128, 128, 3) float32
    """

    target_length = int(sample_rate * duration)

    # -------------------------------------------------------------
    # 1. Load audio & force to EXACT 2 seconds (pad or crop)
    # -------------------------------------------------------------
    audio, sr = librosa.load(file_path, sr=sample_rate)

    if len(audio) < target_length:
        audio = np.pad(audio, (0, target_length - len(audio)), mode="constant")
    else:
        audio = audio[:target_length]

    # -------------------------------------------------------------
    # 2. Compute mel spectrogram (same as training)
    # -------------------------------------------------------------
    mel = librosa.feature.melspectrogram(
        y=audio,
        sr=sample_rate,
        n_fft=n_fft,
        hop_length=hop_length,
        n_mels=n_mels
    )
    mel_db = librosa.power_to_db(mel, ref=np.max)  # log scale

    # -------------------------------------------------------------
    # 3. Resize mel to 128×128
    # -------------------------------------------------------------
    z1 = 128 / mel_db.shape[0]
    z2 = 128 / mel_db.shape[1]
    mel_resized = zoom(mel_db, (z1, z2), order=1)

    # Normalize 0–1
    c0 = (mel_resized - mel_resized.min()) / (mel_resized.max() - mel_resized.min() + 1e-8)

    # -------------------------------------------------------------
    # 4. Delta and Delta-Delta (same pipeline)
    # -------------------------------------------------------------
    delta = librosa.feature.delta(mel_db)
    delta2 = librosa.feature.delta(mel_db, order=2)

    # Resize deltas
    delta_resized = zoom(delta, (128/delta.shape[0], 128/delta.shape[1]), order=1)
    delta2_resized = zoom(delta2, (128/delta2.shape[0], 128/delta2.shape[1]), order=1)

    # Normalize 0–1
    c1 = (delta_resized - delta_resized.min()) / (delta_resized.max() - delta_resized.min() + 1e-8)
    c2 = (delta2_resized - delta2_resized.min()) / (delta2_resized.max() - delta2_resized.min() + 1e-8)

    # -------------------------------------------------------------
    # 5. Stack to (128,128,3)
    # -------------------------------------------------------------
    mel_3ch = np.stack([c0, c1, c2], axis=-1).astype(np.float32)

    # -------------------------------------------------------------
    # 6. Expand for model → shape (1,128,128,3)
    # -------------------------------------------------------------
    return np.expand_dims(mel_3ch, axis=0)

